function paths = build_admittance_simulink(M,D,Ts)
%BUILD_ADMITTANCE_SIMULINK Build a reusable 500 Hz nominal admittance model.
%
% Run after the existing six-axis design script sets M, D and Ts:
%    main
%    design_6axis_admittance
%    addpath(fullfile(pwd,'6D','simulink'))
%    build_admittance_simulink(M,D,Ts)
%
% Creates Admittance_6D.slx and Admittance_6D_Testbench.slx.
% Does NOT generate a production controller or authorize motor motion.

validateattributes(M,{'double'},{'real','finite','positive','size',[6,1]});
validateattributes(D,{'double'},{'real','finite','positive','size',[6,1]});
validateattributes(Ts,{'double'},{'real','finite','positive','scalar'});
assert(abs(Ts-0.002) < 1e-12, ...
    'This model has a fixed 500 Hz execution contract (Ts=0.002).');

% Exactly match 6D/models/admittance_6d_tustin.m.
a = (2*M-D*Ts)./(2*M+D*Ts);
b = Ts./(2*M+D*Ts);
assert(all(abs(a)<1), 'Unstable discrete pole encountered.');
assert(all(a>=0), 'Selected M/D values yield negative discrete poles.');

folder = fileparts(mfilename('fullpath'));
controller = 'Admittance_6D';
bench = 'Admittance_6D_Testbench';
controllerFile = fullfile(folder,[controller '.slx']);
benchFile = fullfile(folder,[bench '.slx']);

% Never erase a manually edited model or an existing design snapshot.
assert(~isfile(controllerFile) && ~isfile(benchFile), ...
    'Model already exists. Move it aside before regenerating.');
assert(~isfile(fullfile(folder,'Admittance_6D_parameters.mat')), ...
    'Design snapshot already exists. Do not silently overwrite it.');
assert(~bdIsLoaded(controller) && ~bdIsLoaded(bench), ...
    'Close models with the target names before building.');

new_system(controller);
set_param(controller,'SolverType','Fixed-step', ...
    'Solver','FixedStepDiscrete', ...
    'FixedStep',num2str(Ts,17), ...
    'StopTime','4');

add_block('simulink/Sources/In1',[controller '/Wrench_6D'], ...
    'PortDimensions','6','Position',[45 205 85 235]);
add_block('simulink/Signal Routing/Demux',[controller '/Split_Wrench'], ...
    'Outputs','6','Position',[145 90 150 470]);
add_block('simulink/Signal Routing/Mux',[controller '/Combine_Twist'], ...
    'Inputs','6','Position',[530 90 535 470]);
add_block('simulink/Sinks/Out1',[controller '/Twist_6D'], ...
    'Position',[610 205 650 235]);

add_line(controller,'Wrench_6D/1','Split_Wrench/1','autorouting','on');
axisName = {'Fx','Fy','Fz','Tx','Ty','Tz'};
for k=1:6
    y=65+72*k;
    name=['Tustin_' axisName{k}];
    % H_i(z) = b_i (z+1)/(z-a_i), exactly equivalent to the
    % existing sample recurrence using w[k] and w[k-1].
    add_block('simulink/Discrete/Discrete Transfer Fcn', ...
        [controller '/' name], ...
        'Numerator',sprintf('[%.17g %.17g]',b(k),b(k)), ...
        'Denominator',sprintf('[1 %.17g]',-a(k)), ...
        'SampleTime',num2str(Ts,17), ...
        'Position',[290 y-22 440 y+22]);
    add_line(controller,sprintf('Split_Wrench/%d',k), ...
        [name '/1'],'autorouting','on');
    add_line(controller,[name '/1'], ...
        sprintf('Combine_Twist/%d',k),'autorouting','on');
end
add_line(controller,'Combine_Twist/1','Twist_6D/1','autorouting','on');
save_system(controller,controllerFile);

% Standalone reference-model testbench; no sensor or robot plant.
new_system(bench);
set_param(bench,'SolverType','Fixed-step', ...
    'Solver','FixedStepDiscrete', ...
    'FixedStep',num2str(Ts,17),'StopTime','4');
add_block('simulink/Sources/From Workspace',[bench '/Six_Axis_Wrench'], ...
    'VariableName','ft_wrench_ts', ...
    'SampleTime',num2str(Ts,17), ...
    'Interpolate','off', ...
    'OutputAfterFinalValue','Holding final value', ...
    'Position',[65 150 215 205]);
add_block('simulink/Ports & Subsystems/Model', ...
    [bench '/Admittance_Controller'], ...
    'ModelName',controller, ...
    'Position',[300 145 470 210]);
add_block('simulink/Sinks/To Workspace',[bench '/Record_Twist'], ...
    'VariableName','twist_ts', ...
    'SaveFormat','Timeseries', ...
    'Position',[570 120 715 160]);
add_block('simulink/Sinks/Scope',[bench '/Twist_Scope'], ...
    'Position',[585 225 620 260]);
add_line(bench,'Six_Axis_Wrench/1', ...
    'Admittance_Controller/1','autorouting','on');
add_line(bench,'Admittance_Controller/1', ...
    'Record_Twist/1','autorouting','on');
add_line(bench,'Admittance_Controller/1', ...
    'Twist_Scope/1','autorouting','on');
save_system(bench,benchFile);

% Immutable snapshot of exactly the parameters used to build coefficients.
save(fullfile(folder,'Admittance_6D_parameters.mat'),'M','D','Ts','a','b');
paths = struct('controller',controllerFile,'testbench',benchFile);
fprintf('Created %s\nCreated %s\n',controllerFile,benchFile);
fprintf('Parameters were snapshotted; rebuild after changing M or D.\n');
open_system(bench);
end
